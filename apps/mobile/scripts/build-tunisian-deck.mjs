// Inlines the Tunisian deck SVGs (assets/decks/tunisian) into src/skins/cafe/tunisianDeck.ts.
// Run from apps/mobile: node scripts/build-tunisian-deck.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = 'assets/decks/tunisian';
const OUT = 'src/skins/cafe/tunisianDeck.ts';

// Crop the source's own black frame; the app's Card draws the border and radius.
const ROOT =
  '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" ' +
  'viewBox="3 3 83 125" preserveAspectRatio="xMidYMid slice">';

function inline(file, id) {
  const xml = readFileSync(join(SRC, file), 'utf8').replace(/<svg[^>]*>/, ROOT);
  // On web every card shares one DOM, so svgo's short ids ("a", "b") must be unique per card.
  return JSON.stringify(
    xml
      .replace(/\bid="([^"]+)"/g, `id="tn${id}-$1"`)
      .replace(/href="#([^"]+)"/g, `href="#tn${id}-$1"`)
      .replace(/url\(#([^)]+)\)/g, `url(#tn${id}-$1)`),
  );
}

const entries = readdirSync(SRC)
  .filter((f) => f.endsWith('.svg') && f !== 'back.svg')
  .sort()
  .map((file) => {
    const id = file.replace('.svg', '');
    return `  '${id}': ${inline(file, id)},`;
  });

writeFileSync(
  OUT,
  `// Generated by scripts/build-tunisian-deck.mjs — do not edit.
// Artwork: "Chkobba" deck by Abjiklam, Wikimedia Commons (https://commons.wikimedia.org/wiki/Category:Chkobba).
// Number cards CC0; court cards CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/). See assets/decks/tunisian/README.md.
import type { CardId } from '@chkobba/rules';

export const TUNISIAN_DECK: Record<CardId, string> = {
${entries.join('\n')}
};

export const TUNISIAN_BACK = ${inline('back.svg', 'back')};
`,
);
console.log(`wrote ${entries.length} cards and the back to ${OUT}`);
